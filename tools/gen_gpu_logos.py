#!/usr/bin/env python3
"""Generate firmware/comfyui_panel/gpu_logos.c : 16x16 vendor marks for LVGL.

Hand-drawn 1-bit masks (no third-party raster files) are emitted as
LV_IMG_CF_TRUE_COLOR_ALPHA images tinted with the vendor colour, so the panel can
show a short GPU model with a brand mark instead of the truncated full name.

Usage:
  tools/gen_gpu_logos.py                # write the C file
  tools/gen_gpu_logos.py --preview p.png  # also render a 10x contact sheet
"""
import struct
import sys
import zlib

SIZE = 16

MASK_NVIDIA = [
    "................",
    "................",
    "................",
    ".....######.....",
    "...##......##...",
    "..#....##....#..",
    ".#....####.....#",
    "#....######....#",
    ".#....####.....#",
    "..#....##....#..",
    "...##......##...",
    ".....######.....",
    "................",
    "................",
    "................",
    "................",
]

MASK_AMD = [
    "................",
    "................",
    "................",
    "................",
    "................",
    "..##...#...#.###",
    ".#..#.##.##.#..#",
    ".#..#.#.#.#.#..#",
    ".####.#.#.#.#..#",
    ".#..#.#...#.#..#",
    ".#..#.#...#.#..#",
    ".#..#.#...#.###.",
    "................",
    "................",
    "................",
    "................",
]

BRANDS = [
    ("nvidia", "GPU_LOGO_NVIDIA", 0x76B900, MASK_NVIDIA),
    ("amd", "GPU_LOGO_AMD", 0xED1C24, MASK_AMD),
]


def rgb565(color: int) -> int:
    r, g, b = (color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def pixel_bytes(mask, color):
    lo, hi = rgb565(color) & 0xFF, (rgb565(color) >> 8) & 0xFF
    out = bytearray()
    for row in mask:
        for ch in row:
            ink = ch != "."
            out += bytes((lo, hi, 0xFF if ink else 0x00))
    return bytes(out)


def write_c(path: str) -> None:
    lines = [
        "// Generated by tools/gen_gpu_logos.py - 16x16 GPU vendor marks (LVGL TRUE_COLOR_ALPHA).",
        "#include <lvgl.h>",
        "#include \"gpu_logos.h\"",
        "",
    ]
    for _, sym, color, mask in BRANDS:
        data = pixel_bytes(mask, color)
        lines.append(f"static const uint8_t {sym.lower()}_px[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append(f"const lv_img_dsc_t {sym} = {{")
        lines.append("  .header.cf = LV_IMG_CF_TRUE_COLOR_ALPHA,")
        lines.append("  .header.always_zero = 0,")
        lines.append(f"  .header.w = {SIZE},")
        lines.append(f"  .header.h = {SIZE},")
        lines.append(f"  .data_size = sizeof({sym.lower()}_px),")
        lines.append(f"  .data = {sym.lower()}_px,")
        lines.append("};")
        lines.append("")
    open(path, "w").write("\n".join(lines))


def write_png(path: str) -> None:
    scale, pad, bg = 10, 8, (13, 18, 32)
    imgs = [(color, mask) for _, _, color, mask in BRANDS]
    w = pad + len(imgs) * (SIZE * scale + pad)
    h = pad + SIZE * scale + pad
    rows = []
    for y in range(h):
        row = bytearray()
        row.append(0)
        for x in range(w):
            c = bg
            bx = x - pad
            for i, (color, mask) in enumerate(imgs):
                ox = i * (SIZE * scale + pad)
                if ox <= bx < ox + SIZE * scale:
                    mx = (bx - ox) // scale
                    my = (y - pad) // scale
                    if 0 <= my < SIZE and 0 <= mx < SIZE and mask[my][mx] != ".":
                        c = ((color >> 16) & 0xFF, (color >> 8) & 0xFF, color & 0xFF)
                    break
            row += bytes(c)
        rows.append(bytes(row))
    raw = b"".join(rows)

    def chunk(tag, body):
        return struct.pack(">I", len(body)) + tag + body + struct.pack(">I", zlib.crc32(tag + body) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(raw, 9))
    png += chunk(b"IEND", b"")
    open(path, "wb").write(png)


if __name__ == "__main__":
    out = "firmware/comfyui_panel/gpu_logos.c"
    write_c(out)
    print("wrote", out)
    if "--preview" in sys.argv:
        p = sys.argv[sys.argv.index("--preview") + 1]
        write_png(p)
        print("preview", p)
